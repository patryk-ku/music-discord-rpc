#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_sanitize_name() {
        assert_eq!(sanitize_name("Spotify"), "spotify");
        assert_eq!(sanitize_name("Google Chrome"), "google_chrome");
        assert_eq!(sanitize_name("  VLC   Media Player!  "), "vlc_media_player");
        assert_eq!(sanitize_name("Cider v2.5"), "cider_v2_5");
    }

    #[test]
    fn test_trim_to_max_bytes() {
        let short = "Hello World".to_string();
        assert_eq!(trim_to_max_bytes(short.clone(), 50), short);

        let ascii = "a".repeat(300);
        let trimmed = trim_to_max_bytes(ascii, 256);
        assert_eq!(trimmed.len(), 256);

        // Multi-byte utf-8: 'ż' is 2 bytes (0xC5 0xBC)
        let utf8_str = "ż".repeat(150); // 300 bytes
        let trimmed_utf8 = trim_to_max_bytes(utf8_str, 256);
        assert!(trimmed_utf8.len() <= 256);
        assert_eq!(trimmed_utf8.len() % 2, 0); // Each 'ż' is 2 bytes, so length must remain even
    }

    #[test]
    fn test_build_trimmed_url() {
        let prefix = "https://www.youtube.com/results?search_query=";
        let query = "Queen - Bohemian Rhapsody";
        let url = build_trimmed_url(prefix, query);
        assert!(url.starts_with(prefix));
        assert!(url.len() <= MAX_URL_LEN);

        let long_query = "very long song name ".repeat(30);
        let long_url = build_trimmed_url(prefix, &long_query);
        assert!(long_url.len() <= MAX_URL_LEN);
        assert!(long_url.starts_with(prefix));
    }
}
